document.addEventListener("DOMContentLoaded", () => {
  const langButtons = document.querySelectorAll(".lang-btn");
  
  // Set default language
  let currentLang = localStorage.getItem("taxfree_lang") || "ko";
  
  // Apply translation
  const applyLanguage = (lang) => {
    const data = translations[lang];
    if (!data) return;
    
    // Animate content change (fade-out, change text, fade-in)
    const container = document.querySelector(".app-container");
    container.classList.add("fade-out");
    
    setTimeout(() => {
      // Direct text replacements
      document.querySelectorAll("[data-translate]").forEach(elem => {
        const key = elem.getAttribute("data-translate");
        if (data[key]) {
          elem.innerHTML = data[key];
        }
      });
      
      // Update SVG Map labels dynamically
      const mapCurrentText = document.getElementById("map-label-current");
      const mapCheckoutText = document.getElementById("map-label-checkout");
      const mapKioskText = document.getElementById("map-label-kiosk");
      
      if (mapCurrentText && data.mapCurrent) mapCurrentText.textContent = data.mapCurrent;
      if (mapCheckoutText && data.mapCheckout) mapCheckoutText.textContent = data.mapCheckout;
      if (mapKioskText && data.mapKiosk) mapKioskText.textContent = data.mapKiosk;
      
      // Update page title
      document.title = "베리뉴약국 " + data.title;
      
      // Update HTML lang attribute
      document.documentElement.lang = lang;
      
      container.classList.remove("fade-out");
    }, 200);
    
    // Update active button state
    langButtons.forEach(btn => {
      if (btn.getAttribute("data-lang") === lang) {
        btn.classList.add("active");
        btn.setAttribute("aria-selected", "true");
      } else {
        btn.classList.remove("active");
        btn.setAttribute("aria-selected", "false");
      }
    });
    
    // Store selected language
    localStorage.setItem("taxfree_lang", lang);
  };
  
  // Add click events to buttons
  langButtons.forEach(btn => {
    btn.addEventListener("click", () => {
      const selectedLang = btn.getAttribute("data-lang");
      if (selectedLang !== currentLang) {
        currentLang = selectedLang;
        applyLanguage(currentLang);
      }
    });
  });
  
  // Initialize on load
  applyLanguage(currentLang);
});
